namespace Content.Client._CE.Planets.Hellpods;

[GenerateTypedNameReferences]
public sealed partial class CEHellpodConsoleWindow : BaseWindow
{
    private readonly IGameTiming _timing = IoCManager.Resolve<IGameTiming>();
    private readonly TerminalFrame _frame;
    private readonly LaunchProgress _launchFill;
    private (ProtoId<CEHellpodTypePrototype>? Type, int Hatches) _shownRecipe;
    private TimeSpan? _launchHeldAt;
    private TimeSpan? _awaitingConfirmUntil;

    public CEHellpodChart Chart => TargetChart;
    public Action<Vector2, float, CEHellpodHoldAction>? Confirm;

    public CEHellpodConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        _frame = new TerminalFrame(Header, Footer) { MouseFilter = MouseFilterMode.Ignore };
        AddChild(_frame);
        var resources = IoCManager.Resolve<IResourceCache>();
        _launchFill = new LaunchProgress(ConfirmButton,
            (StyleBoxTexture) ConfirmButton.StyleBoxOverride!,
            resources.GetTexture("/Textures/Interface/Nano/Monotone/monotone_button_filled.svg.96dpi.png"));
        LaunchButtonArea.AddChild(_launchFill);
        _launchFill.SetPositionInParent(0);

        CloseButton.OnPressed += _ => Close();
        AscendButton.OnPressed += _ => Chart.ChangeDepth(1);
        DescendButton.OnPressed += _ => Chart.ChangeDepth(-1);
        SmallerButton.OnPressed += _ => Chart.ChangeRadius(-4);
        LargerButton.OnPressed += _ => Chart.ChangeRadius(4);
        ConfirmButton.OnButtonDown += _ => SetLaunchHeld(true);
        ConfirmButton.OnButtonUp += _ =>
        {
            if (!TryCompleteHold())
                SetLaunchHeld(false);
        };
        CloseButton.Label.AddStyleClass("ConsoleHeading");
        ConfirmButton.Label.FontOverride = resources.GetFont("/Fonts/RobotoMono/RobotoMono-Bold.ttf", size: 24);
        foreach (var button in new[] { AscendButton, DescendButton, SmallerButton, LargerButton })
            button.Label.AddStyleClass("ConsoleText");
        SetTheme(false);
        UpdateSilo(Chart.State);
        UpdateReadout();
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos) =>
        relativeMousePos.Y <= Header.Height + 2 ? DragMode.Move : DragMode.None;

    private void SetLaunchHeld(bool held)
    {
        if (_awaitingConfirmUntil.HasValue || held == _launchHeldAt.HasValue)
            return;

        _launchHeldAt = held ? _timing.RealTime : null;
        UpdateRadiusControls();
        Confirm?.Invoke(Chart.Center, Chart.Radius, held ? CEHellpodHoldAction.Start : CEHellpodHoldAction.Cancel);
    }

    private void UpdateRadiusControls()
    {
        Chart.AimLockedLocally = _launchHeldAt.HasValue || _awaitingConfirmUntil.HasValue;
        SmallerButton.Disabled = !Chart.CanAim || Chart.Radius <= CEHellpodConsoleComponent.MinRadius;
        LargerButton.Disabled = !Chart.CanAim || Chart.Radius >= CEHellpodConsoleComponent.MaxRadius;
    }

    private bool TryCompleteHold()
    {
        var now = _timing.RealTime;
        if (_launchHeldAt is not { } start || now - start < CEHellpodConsoleComponent.ConfirmTime)
            return false;

        _launchHeldAt = null;
        _awaitingConfirmUntil = now + TimeSpan.FromSeconds(6);
        Confirm?.Invoke(Chart.Center, Chart.Radius, CEHellpodHoldAction.Complete);
        return true;
    }

    public void RejectConfirm()
    {
        _awaitingConfirmUntil = null;
        UpdateReadout();
    }

    public void Apply(CEHellpodConsoleState state)
    {
        if ((state.Planet != null) != (Chart.State.Planet != null))
            SetTheme(state.Planet != null);

        Chart.Apply(state);
        UpdateSilo(state);
        UpdateReadout();
    }

    private void SetTheme(bool hasPlanet)
    {
        var tint = Color.FromHex(hasPlanet ? "#33e633" : "#ff9a36");
        _frame.Tint = tint;
        Header.Modulate = SiloColumn.Modulate = PlanetLabel.Modulate = AltitudeControls.Modulate =
            TargetLabel.Modulate = IntegrityLabel.Modulate = LaunchControls.Modulate = Footer.Modulate = tint;
        if (Chassis.PanelOverride is StyleBoxFlat chassis)
            chassis.BackgroundColor = Color.FromHex(hasPlanet ? "#0b230b" : "#27180d");

        if (ChartFrame.PanelOverride is StyleBoxFlat chart)
            chart.BorderColor = tint;
    }

    private void UpdateSilo(CEHellpodConsoleState state)
    {
        SiloLabel.Text = Loc.GetString(state.SiloConnected ? "ce-hellpod-console-silo-connected" : "ce-hellpod-console-silo-disconnected");
        var recipe = (state.PodType, state.Hatches);
        if (_shownRecipe == recipe)
            return;

        _shownRecipe = recipe;
        MaterialRows.RemoveAllChildren();
        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        if (state.PodType is not { } id || !prototypes.TryIndex(id, out var type))
            return;

        var sprites = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
        foreach (var (materialId, amount) in type.Materials)
            MaterialRows.AddChild(new MaterialCostRow(
                prototypes.Index(materialId), (long) amount * state.Hatches, sprites, "ConsoleText", clipName: true));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateReadout();
    }

    private void UpdateProblems()
    {
        var (shields, hull) = Chart.GetWarnings();
        var planetShield = Chart.State.PlanetShielded;
        NoTargetWarning.Visible = Chart.State.Planet == null;
        NoSiloWarning.Visible = !Chart.State.SiloConnected;
        UnfundedWarning.Visible = Chart.State.SiloConnected && Chart.State.Hatches > 0 &&
                                  Chart.State.LaunchAt == null && !Chart.State.CanFundVolley;
        ProblemsPanel.Visible = NoTargetWarning.Visible || NoSiloWarning.Visible || UnfundedWarning.Visible ||
                                planetShield || shields > 0 || hull;
        PlanetShieldWarning.Visible = planetShield;
        RadialShieldWarning.Visible = shields > 0;
        if (shields > 0)
            RadialShieldHeading.Text = Loc.GetString("ce-hellpod-console-radial-shield", ("count", shields));
        HullWarning.Visible = hull;

        var shieldHits = shields + (planetShield ? 1 : 0);
        var integrity = Math.Max(0, CEHellpodComponent.FullIntegrity - shieldHits * CEHellpodComponent.ShieldIntegrityLoss);
        Chart.EstimatedIntegrity = integrity;
        IntegrityLabel.Text = Loc.GetString("ce-hellpod-console-integrity", ("percent", integrity));
    }

    private void UpdateReadout()
    {
        UpdateProblems();
        var state = Chart.State;
        var hasPlanet = state.Planet != null;
        PlanetLabel.Text = state.Planet;
        TargetLabel.Text = hasPlanet
            ? Loc.GetString("ce-hellpod-console-coordinates", ("x", MathF.Round(Chart.Center.X)), ("y", MathF.Round(Chart.Center.Y)))
            : null;
        AltitudeLabel.Text = hasPlanet
            ? Loc.GetString("ce-hellpod-console-depth", ("layer", Chart.Depth - state.MinDepth + 1),
                ("total", state.MaxDepth - state.MinDepth + 1))
            : Loc.GetString("ce-hellpod-console-depth-empty");
        RadiusLabel.Text = Loc.GetString("ce-hellpod-console-radius", ("radius", Chart.Radius));

        var charging = state.FireAt != null;
        var lockDeadline = state.FireAt ?? state.LaunchAt;
        if (lockDeadline is { } end)
        {
            var duration = charging ? CEHellpodConsoleComponent.LaunchDelay : CEHellpodConsoleComponent.BoardingTime;
            var remaining = Math.Clamp((end - _timing.CurTime).TotalSeconds, 0, duration.TotalSeconds);
            var time = TimeSpan.FromMilliseconds(Math.Ceiling(remaining * 100) * 10).ToString(@"mm\:ss\:ff");
            StageLabel.Text = Loc.GetString("ce-hellpod-console-countdown", ("time", time),
                ("occupied", state.Occupied), ("hatches", state.Hatches));
        }
        else
        {
            StageLabel.Text = null;
        }

        AscendButton.Disabled = !hasPlanet || Chart.Depth >= state.MaxDepth;
        DescendButton.Disabled = !hasPlanet || Chart.Depth <= state.MinDepth;
        var locked = lockDeadline != null;
        if (locked || _awaitingConfirmUntil is { } deadline && _timing.RealTime >= deadline)
            _awaitingConfirmUntil = null;

        var canLaunch = hasPlanet && state.CanFundVolley && !locked;
        if (canLaunch && UserInterfaceManager.ControlFocused == ConfirmButton)
            TryCompleteHold();

        ConfirmButton.Disabled = !canLaunch || _awaitingConfirmUntil.HasValue;
        if (locked)
        {
            _launchHeldAt = null;
            ConfirmButton.Text = Loc.GetString(charging ? "ce-hellpod-console-charging" : "ce-hellpod-console-locked");
            var pulse = 0.8f + 0.2f * (float) Math.Sin(_timing.RealTime.TotalSeconds * Math.PI);
            ConfirmButton.Modulate = charging ? Color.Gray : Color.White.WithAlpha(pulse);
        }
        else
        {
            ConfirmButton.Text = Loc.GetString("ce-hellpod-console-confirm");
            ConfirmButton.Modulate = ConfirmButton.Disabled ? Color.Gray : Color.White;
            if (ConfirmButton.Disabled || UserInterfaceManager.ControlFocused != ConfirmButton)
                SetLaunchHeld(false);
        }

        UpdateRadiusControls();
        var progress = _launchHeldAt is { } start
            ? (float) Math.Clamp((_timing.RealTime - start).TotalSeconds / CEHellpodConsoleComponent.ConfirmTime.TotalSeconds, 0, 1)
            : 0f;
        _launchFill.SetProgress(_awaitingConfirmUntil.HasValue ? 1f : progress);
    }

    private sealed class LaunchProgress : Control
    {
        private readonly Control _button;
        private readonly StyleBoxTexture _fill;

        public LaunchProgress(Control button, StyleBoxTexture outline, Texture fillTexture)
        {
            _button = button;
            _fill = new StyleBoxTexture(outline) { Texture = fillTexture, Modulate = Color.White.WithAlpha(0.25f) };
            HorizontalAlignment = HAlignment.Left;
            RectClipContent = true;
            MouseFilter = MouseFilterMode.Ignore;
        }

        public void SetProgress(float progress)
        {
            var pixels = MathF.Round(_button.PixelWidth * progress);
            Visible = pixels > 0;
            if (Visible && SetWidth != pixels / UIScale)
                SetWidth = pixels / UIScale;
        }

        // Draw the full-size shape and reveal it through this control's clip.
        protected override void Draw(DrawingHandleScreen handle) => _fill.Draw(handle, _button.PixelSizeBox, UIScale);
    }

    private sealed class TerminalFrame(Control header, Control footer) : Control
    {
        public Color Tint { get; set; }

        protected override void Draw(DrawingHandleScreen handle)
        {
            // Use one pixel-aligned stroke for the frame and both dividers at any UI scale.
            var stroke = Math.Max(1, (int) MathF.Round(2 * UIScale));
            var originY = GlobalPixelPosition.Y;
            var headerY = header.GlobalPixelPosition.Y + header.PixelHeight - originY - stroke;
            var footerY = footer.GlobalPixelPosition.Y - originY;
            handle.DrawRect(new UIBox2(0, 0, PixelWidth, stroke), Tint);
            handle.DrawRect(new UIBox2(0, PixelHeight - stroke, PixelWidth, PixelHeight), Tint);
            handle.DrawRect(new UIBox2(0, 0, stroke, PixelHeight), Tint);
            handle.DrawRect(new UIBox2(PixelWidth - stroke, 0, PixelWidth, PixelHeight), Tint);
            handle.DrawRect(new UIBox2(0, headerY, PixelWidth, headerY + stroke), Tint);
            handle.DrawRect(new UIBox2(0, footerY, PixelWidth, footerY + stroke), Tint);
        }
    }
}
