using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Ships;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Mono.ShipShieldShell;

[GenerateTypedNameReferences]
public sealed partial class ShipShieldProjectorWindow : FancyWindow
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IGameTiming _timing = default!;

    private static readonly Color ChargeRed = Color.FromHex("#A33F49");
    private static readonly Color ChargeGreen = Color.FromHex("#337E50");
    private readonly StyleBoxFlat _chargeFill = new(ChargeGreen);
    private EntityUid _owner;
    private (bool Enabled, string Status, int Seconds)? _lastControls;
    private (int Charge, int Capacity, int MaxCapacity)? _lastCharge;
    public event Action? ToggleRequested;

    public ShipShieldProjectorWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        ChargeBar.ForegroundStyleBoxOverride = _chargeFill;
        StallIndicator.FontColorOverride = Color.Salmon;
        DrawBar.ForegroundStyleBoxOverride = new StyleBoxFlat(Color.FromHex("#3B618B"));
        ToggleButton.OnPressed += _ => ToggleRequested?.Invoke();
    }

    public void SetEntity(EntityUid uid)
    {
        _owner = uid;
        EntityView.SetEntity(uid);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_entities.TryGetComponent(_owner, out ShipShieldProjectorComponent? projector))
            return;

        UpdateCharge(projector);
        var now = _timing.CurTime;
        var respoolUntil = projector.RespoolUntil;
        if (projector.IsShattering)
        {
            var shatterEnd = projector.StartedAt + projector.AnimationDuration(projector.State);
            if (shatterEnd > respoolUntil)
                respoolUntil = shatterEnd;
        }

        var stalled = projector.RechargeStalledUntil > now;
        var respooling = respoolUntil > now;
        var eta = respooling ? respoolUntil : projector.RechargeStalledUntil;
        var seconds = Math.Max(0, (int) Math.Ceiling((eta - now).TotalSeconds));
        var running = _entities.System<SharedShipShieldShellSystem>().IsSolid(projector);
        var status = respooling ? "mono-ship-shield-ui-respooling" :
            stalled ? "mono-ship-shield-ui-stalled" :
            running ? "mono-ship-shield-ui-running" :
            projector.State is ShipShieldShellState.Starting or ShipShieldShellState.Active
                ? "mono-ship-shield-ui-spooling" : "mono-ship-shield-ui-offline";
        StallIndicator.Visible = stalled;
        var controls = (projector.RequestsPower, status, seconds);
        if (_lastControls == controls)
            return;

        _lastControls = controls;
        ToggleButton.Text = Loc.GetString(projector.RequestsPower ? "mono-ship-shield-ui-lower" : "mono-ship-shield-ui-raise");
        StatusLabel.Text = Loc.GetString(status);
        StatusLabel.FontColorOverride = respooling ? Color.Salmon :
            stalled ? Color.Gold : running ? Color.LightGreen : null;
        EtaTitle.Visible = EtaLabel.Visible = seconds > 0;
        if (seconds > 0)
            EtaLabel.Text = Loc.GetString("mono-ship-shield-ui-seconds", ("seconds", seconds));
    }

    private void UpdateCharge(ShipShieldProjectorComponent projector)
    {
        var charge = projector.MaxCapacity > 0f ? projector.Capacity / projector.MaxCapacity : 0f;
        ChargeBar.Value = charge;
        _chargeFill.BackgroundColor = Color.InterpolateBetween(ChargeRed, ChargeGreen,
            Math.Clamp((charge - 0.25f) / 0.75f, 0f, 1f));

        var labels = (Charge: (int) MathF.Round(charge * 100f), Capacity: (int) MathF.Round(projector.Capacity),
            MaxCapacity: (int) MathF.Round(projector.MaxCapacity));
        if (_lastCharge == labels)
            return;

        _lastCharge = labels;
        ChargeLabel.Text = Loc.GetString("mono-ship-shield-ui-percent", ("percent", labels.Charge));
        CapacityLabel.Text = Loc.GetString("mono-ship-shield-ui-capacity",
            ("remaining", labels.Capacity), ("max", labels.MaxCapacity));
    }

    public void UpdateState(ShipShieldProjectorUiState state)
    {
        var requesting = state.RequestedPower > 0f;
        var draw = requesting ? Math.Clamp(state.ReceivedPower / state.RequestedPower, 0f, 1f) : 0f;
        DrawBar.Value = draw;
        DrawPercentLabel.Text = requesting ? FormatPercent(draw) : Loc.GetString("mono-ship-shield-ui-no-demand");
        DrawPowerLabel.Text = FormatPower(state.ReceivedPower);

        ToggleButton.Disabled = state.Locked;
    }

    private static string FormatPercent(float fraction) =>
        Loc.GetString("mono-ship-shield-ui-percent", ("percent", (int) MathF.Round(fraction * 100f)));

    private static string FormatPower(float watts)
    {
        var (unit, divisor) = watts switch
        {
            >= 1_000_000f => ("mono-ship-shield-ui-megawatts", 1_000_000f),
            >= 1_000f => ("mono-ship-shield-ui-kilowatts", 1_000f),
            _ => ("mono-ship-shield-ui-watts", 1f),
        };
        return Loc.GetString(unit, ("power", (watts / divisor).ToString("0.##")));
    }
}
