using System.Linq;
using Content.Client.Message;
using Content.Shared._Mono.Cloning;
using Content.Shared.Cloning.CloningConsole;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Mono.Cloning.UI;

[GenerateTypedNameReferences]
public sealed partial class GeneticCloningConsoleWindow : DefaultWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<int>? OnCloneRecord;
    public event Action<int>? OnDeleteRecord;

    private int? _selectedId;
    private readonly ButtonGroup _recordGroup = new();
    private GeneticCloningConsoleBoundUserInterfaceState? _lastUpdate;

    public GeneticCloningConsoleWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        CloneButton.OnPressed += _ =>
        {
            if (_selectedId != null)
                OnCloneRecord?.Invoke(_selectedId.Value);
        };
        DeleteButton.OnPressed += _ =>
        {
            if (_selectedId != null)
                OnDeleteRecord?.Invoke(_selectedId.Value);
        };
        SearchBar.OnTextChanged += _ =>
        {
            if (_lastUpdate != null)
                Populate(_lastUpdate);
        };
    }

    public void Populate(GeneticCloningConsoleBoundUserInterfaceState state)
    {
        _lastUpdate = state;

        PopulateRecords(state);

        // I should have just had AI do this, fuck ui
        if (state.ClonerConnected)
        {
            if (!state.ClonerInRange)
            {
                CloningPodFar.Visible = true;
                CloningPodContents.Visible = false;
                CloningPodMissing.Visible = false;
                return;
            }

            CloningPodContents.Visible = true;
            CloningPodFar.Visible = false;
            CloningPodMissing.Visible = false;

            ClonerBrainActivity.SetMarkup(Loc.GetString(state.MindPresent ? "cloning-console-mind-present-text" : "cloning-console-no-mind-activity-text"));
            // catch shit for occupation label
            ClonerInfoLabel.SetMarkup(state.ClonerBodyInfo != null ?
                Loc.GetString("cloning-console-window-pod-id", ("podOccupantName", state.ClonerBodyInfo)) :
                Loc.GetString("cloning-console-window-id-blank"));
        }
        else
        {
            // error stuff
            CloningPodContents.Visible = false;
            CloningPodFar.Visible = false;
            CloningPodMissing.Visible = true;
        }
    }

    private void PopulateRecords(GeneticCloningConsoleBoundUserInterfaceState state)
    {
        DatabaseLabel.Text = state.DatabaseName != null
            ? Loc.GetString("genetic-database-name", ("name", state.DatabaseName))
            : Loc.GetString("genetic-database-none");

        if (_selectedId != null && state.Records.All(r => r.Id != _selectedId))
            _selectedId = null;

        var filter = SearchBar.Text.Trim();
        var shown = state.Records // I stole this
            .Where(r => filter.Length == 0 || r.Name.Contains(filter, StringComparison.CurrentCultureIgnoreCase))
            .ToList();

        RecordList.RemoveAllChildren();
        foreach (var record in shown)
        {
            RecordList.AddChild(CreateRow(record));
        }

        NoRecordsLabel.Visible = shown.Count == 0;
        NoRecordsLabel.Text = state.DatabaseName == null
            ? Loc.GetString("genetic-database-none")
            : Loc.GetString("cloning-console-window-no-records");

        PopulateDetails(state);
    }

    private void PopulateDetails(GeneticCloningConsoleBoundUserInterfaceState state)
    {
        var selected = state.Records.FirstOrDefault(r => r.Id == _selectedId);
        RecordDetails.Visible = selected != null;
        NoSelectionLabel.Visible = selected == null;
        if (selected == null)
            return;

        RecordNameLabel.Text = selected.Name;
        RecordSpeciesLabel.Text = selected.Species;
        RecordScannedLabel.Text = Loc.GetString("cloning-console-window-scanned-ago",
            ("time", FormatAge(_timing.CurTime - selected.ScannedAt)));
        RecordStatusLabel.SetMarkup(Loc.GetString(StatusExplanation(selected.Status)));

        var podReady = state.ClonerConnected && state.ClonerInRange && state.CloningStatus == ClonerStatus.Ready;
        CloneButton.Disabled = selected.Status != GeneticRecordStatus.Cloneable || !podReady;
        CloningActivity.Text = Loc.GetString(state.CloningStatus switch
        {
            ClonerStatus.NoClonerDetected => "cloning-console-component-msg-no-cloner",
            ClonerStatus.ClonerOccupied => "cloning-console-component-msg-occupied",
            ClonerStatus.OccupantMetaphyiscal => "cloning-console-component-msg-already-alive",
            _ => "cloning-console-component-msg-ready",
        });
    }

    private Control CreateRow(GeneticRecordEntry record)
    {
        var button = new Button
        {
            Text = Loc.GetString("cloning-console-window-record-row", ("name", record.Name), ("species", record.Species)),
            ToggleMode = true,
            Group = _recordGroup,
            Pressed = record.Id == _selectedId,
            HorizontalExpand = true,
            ClipText = true,
        };
        button.OnPressed += _ =>
        {
            _selectedId = record.Id;
            if (_lastUpdate != null)
                PopulateDetails(_lastUpdate);
        };

        var status = new Label
        {
            Text = Loc.GetString(StatusName(record.Status)),
            FontColorOverride = StatusColor(record.Status),
            Margin = new Thickness(5, 0, 0, 0),
            MinWidth = 70,
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 2),
        };
        row.AddChild(button);
        row.AddChild(status);
        return row;
    }

    private static string FormatAge(TimeSpan age)
    {
        if (age < TimeSpan.Zero)
            age = TimeSpan.Zero;

        return age.TotalHours >= 1
            ? $"{(int)age.TotalHours}:{age.Minutes:D2}:{age.Seconds:D2}"
            : $"{age.Minutes:D2}:{age.Seconds:D2}";
    }

    private static string StatusName(GeneticRecordStatus status)
    {
        return status switch
        {
            GeneticRecordStatus.Cloneable => "genetic-record-status-cloneable",
            GeneticRecordStatus.Alive => "genetic-record-status-alive",
            GeneticRecordStatus.Offline => "genetic-record-status-offline",
            GeneticRecordStatus.MovedOn => "genetic-record-status-moved-on",
            _ => "genetic-record-status-lost",
        };
    }

    private static string StatusExplanation(GeneticRecordStatus status)
    {
        return status switch
        {
            GeneticRecordStatus.Cloneable => "genetic-record-status-cloneable-desc",
            GeneticRecordStatus.Alive => "genetic-record-status-alive-desc",
            GeneticRecordStatus.Offline => "genetic-record-status-offline-desc",
            GeneticRecordStatus.MovedOn => "genetic-record-status-moved-on-desc",
            _ => "genetic-record-status-lost-desc",
        };
    }

    private static Color StatusColor(GeneticRecordStatus status)
    {
        return status switch
        {
            GeneticRecordStatus.Cloneable => Color.LimeGreen,
            GeneticRecordStatus.Alive or GeneticRecordStatus.Offline => Color.Gray,
            _ => Color.Red,
        };
    }
}
