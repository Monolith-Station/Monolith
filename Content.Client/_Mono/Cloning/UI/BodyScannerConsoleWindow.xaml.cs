using Content.Shared._Mono.Cloning;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Mono.Cloning.UI;

[GenerateTypedNameReferences]
public sealed partial class BodyScannerConsoleWindow : DefaultWindow
{
    public BodyScannerConsoleWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void Populate(BodyScannerConsoleBoundUserInterfaceState state)
    {
        OccupantLabel.Text = state.Status switch
        {
            BodyScanStatus.NoScanner => Loc.GetString("body-scanner-console-window-no-scanner"),
            BodyScanStatus.ScannerFar => Loc.GetString("body-scanner-console-window-scanner-far"),
            BodyScanStatus.Empty => Loc.GetString("body-scanner-console-window-empty"),
            _ => state.OccupantName ?? Loc.GetString("generic-unknown"),
        };

        StatusLabel.Text = state.Status switch
        {
            BodyScanStatus.Invalid => state.FailReason ?? string.Empty,
            BodyScanStatus.Ready when state.OnFile => Loc.GetString("body-scanner-console-window-on-file"),
            BodyScanStatus.Ready => Loc.GetString("body-scanner-console-window-ready"),
            _ => string.Empty,
        };

        DatabaseLabel.Text = state.DatabaseName != null
            ? Loc.GetString("genetic-database-name", ("name", state.DatabaseName))
            : Loc.GetString("genetic-database-none");

        ScanButton.Disabled = state.Status != BodyScanStatus.Ready || state.DatabaseName == null;
    }
}
