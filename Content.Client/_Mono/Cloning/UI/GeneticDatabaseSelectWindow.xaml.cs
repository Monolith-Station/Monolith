using Content.Shared._Mono.Cloning;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.AutoGenerated;

namespace Content.Client._Mono.Cloning.UI;

[GenerateTypedNameReferences]
public sealed partial class GeneticDatabaseSelectWindow : DefaultWindow
{
    public event Action<int>? OnDatabaseSelected;

    public GeneticDatabaseSelectWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void Populate(GeneticDatabaseSelectBoundUserInterfaceState state)
    {
        Databases.Clear();
        foreach (var entry in state.Databases)
        {
            var item = Databases.AddItem(entry.Name);
            item.Selected = entry.Id == state.SelectedId;
            item.OnSelected += _ => OnDatabaseSelected?.Invoke(entry.Id);
        }
    }
}