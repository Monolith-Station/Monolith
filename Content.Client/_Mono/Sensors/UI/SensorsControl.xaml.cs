using System.Linq;
using Content.Shared._Mono.Sensors;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Mono.Sensors.UI;

[GenerateTypedNameReferences]
public sealed partial class SensorsControl : BoxContainer
{
    public event Action<SensorsSetEmconMessage>? OnEmcon;
    public event Action<SensorsSetArcMessage>? OnArc;
    public event Action<SensorsSetDatalinkMessage>? OnDatalink;

    public SensorsControl()
    {
        RobustXamlLoader.Load(this);
        DatalinkApply.OnPressed += _ =>
        {
            var codes = DatalinkEdit.Text
                .Split(new[] { ' ', ',', ';' }, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .ToList();
            OnDatalink?.Invoke(new SensorsSetDatalinkMessage { Codes = codes });
        };
    }

    public void UpdateState(SensorsBuiState? state)
    {
        HardwareBox.RemoveAllChildren();
        ContactsBox.RemoveAllChildren();

        if (state == null)
            return;

        foreach (var h in state.Hardware)
        {
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 1)
            };

            var text = string.Empty;
            var type = Loc.GetString($"gunnery-emcon-sensor-{h.SensorType}");
            if (h.SensorType == SensorType.ActiveRadar || h.SensorType == SensorType.Jammer)
                text = Loc.GetString($"gunnery-emcon-sensor-info-emitter", ("name", h.Name), ("type", type), ("output", h.TransmitWatts));
            if (h.SensorType == SensorType.PassiveRadar || h.SensorType == SensorType.Infrared)
                text = Loc.GetString($"gunnery-emcon-sensor-info-passive", ("name", h.Name), ("type", type), ("sensitivity", h.Sensitivity));
            row.AddChild(new Label
            {
                Text = text,
                HorizontalExpand = true,
                MinWidth = 180,
                FontColorOverride = Color.Lime,
            });

            var power = new Button
            {
                Text = h.Enabled ? "ON" : "OFF",
                ToggleMode = true,
                Pressed = h.Enabled,
                MinWidth = 48,
            };
            var ent = h.Entity;
            var active = h.ActiveMode;
            power.OnPressed += args =>
            {
                OnEmcon?.Invoke(new SensorsSetEmconMessage
                {
                    Sensor = ent,
                    Enabled = args.Button.Pressed,
                    ActiveMode = active,
                });
            };
            row.AddChild(power);

            if (h.SensorType is SensorType.ActiveRadar or SensorType.Jammer)
            {
                var emit = new Button
                {
                    Text = h.ActiveMode ? "EMIT" : "STBY",
                    ToggleMode = true,
                    Pressed = h.ActiveMode,
                    Disabled = !h.Enabled || !h.Powered,
                    MinWidth = 56,
                };
                var enabled = h.Enabled;
                emit.OnPressed += args =>
                {
                    OnEmcon?.Invoke(new SensorsSetEmconMessage
                    {
                        Sensor = ent,
                        Enabled = enabled,
                        ActiveMode = args.Button.Pressed,
                    });
                };
                row.AddChild(emit);
            }

            if (h.ArcDegrees < 360f)
            {
                row.AddChild(new Label { Text = $"{(h.ArcOffset - 90f) * -1:F0}°", MinWidth = 40 });
                var left = new Button { Text = "<", MinWidth = 28 };
                var right = new Button { Text = ">", MinWidth = 28 };
                var offset = h.ArcOffset;
                left.OnPressed += _ => OnArc?.Invoke(new SensorsSetArcMessage
                {
                    Sensor = ent,
                    ArcOffsetDegrees = offset + 15f,
                });
                right.OnPressed += _ => OnArc?.Invoke(new SensorsSetArcMessage
                {
                    Sensor = ent,
                    ArcOffsetDegrees = offset - 15f,
                });
                row.AddChild(left);
                row.AddChild(right);
            }

            if (!h.Powered)
                row.Modulate = Color.FromHex("#884444");

            HardwareBox.AddChild(row);
        }

        foreach (var c in state.Contacts.OrderBy(c => c.Range))
        {
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 1)
            };

            row.AddChild(new Label
            {
                Text = $"{c.Range:F0}m",
                MinWidth = 80,
                HorizontalAlignment = HAlignment.Left,
                FontColorOverride = Color.Lime,
            });
            row.AddChild(new Label
            {
                Text = $"{c.BearingDegrees:F0}°",
                MinWidth = 80,
                HorizontalAlignment = HAlignment.Left,
                FontColorOverride = Color.Lime,
            });
            row.AddChild(new Label
            {
                Text = c.Sources,
                MinWidth = 110,
                HorizontalAlignment = HAlignment.Left,
                FontColorOverride = Color.Lime,
            });
            row.AddChild(new Label
            {
                Text = $"{c.Rcs:F0}m^2",
                MinWidth = 110,
                HorizontalAlignment = HAlignment.Left,
                FontColorOverride = Color.Lime,
            });
            row.AddChild(new Label
            {
                Text = c.IrSignature > 0 ? $"{c.IrSignature:F0}" : "—",
                MinWidth = 120,
                HorizontalAlignment = HAlignment.Left,
                FontColorOverride = Color.Lime,
            });
            row.AddChild(new Label
            {
                Text = c.ActiveRadarWatts > 0 ? Loc.GetString($"gunnery-emcon-ars-value", ("output", c.ActiveRadarWatts)) : "—",
                MinWidth = 110,
                HorizontalAlignment=HAlignment.Left,
                FontColorOverride = Color.Lime,
            });
            row.AddChild(new Label
            {
                Text = c.JamStrength > 0 ? $"{c.JamStrength / 100:F1}mW" : "—",
                MinWidth = 110,
                HorizontalAlignment=HAlignment.Left,
                FontColorOverride = Color.Lime,
            });
            row.AddChild(new Label
            {
                Text = c.Name ?? c.Target.ToString(),
                HorizontalExpand = true,
                HorizontalAlignment=HAlignment.Left,
                FontColorOverride = Color.Lime,
            });

            ContactsBox.AddChild(row);
        }

        DatalinkEdit.Text = string.Join(' ', state.DatalinkCodes);
    }
}
