using System.Linq;
using Content.Client.UserInterface.Controls.FancyTree;
using Content.Shared._Mono.Shipyard;
using Content.Shared._NF.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.ContentPack;
using Robust.Shared.Prototypes;

namespace Content.Client._Mono.Shipyard.UI;

[GenerateTypedNameReferences]
public sealed partial class VesselReferenceWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _protos = default!;
    [Dependency] private ILocalizationManager _loc = default!;

    private List<VesselReferenceEntry> _all = new();
    private readonly Dictionary<string, VesselReferenceEntry> _byId = new();
    private VesselReferenceCatalog? _catalog;


    public VesselReferenceWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchBar.OnTextChanged += _ => RefreshTree();
        VesselTree.OnSelectedItemChanged += OnTreeSelected;

        Rebuild();
    }

    public void Rebuild()
    {
        _catalog = new VesselReferenceCatalog(
            _protos,
            _loc,
            IoCManager.Resolve<IResourceManager>());

        _all = _catalog.Build();
        _byId.Clear();
        foreach (var e in _all)
        {
            _byId[e.Id] = e;
        }

        RefreshTree();
        ClearDetail();
    }

    private void RefreshTree()
    {
        VesselTree.Clear();

        var filter = SearchBar.Text?.Trim() ?? string.Empty;

        var filtered = _all.Where(e =>
            filter.Length == 0 ||
            e.Name.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
            e.Id.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
            e.Shipyard.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
            e.Classes.Any(c => c.Contains(filter, StringComparison.OrdinalIgnoreCase)));

        foreach (var group in filtered
                     .GroupBy(e => string.IsNullOrWhiteSpace(e.Shipyard) ? "Other" : e.Shipyard)
                     .OrderBy(g => g.Key, StringComparer.OrdinalIgnoreCase))
        {
            var groupNode = VesselTree.AddItem();
            groupNode.Label.Text = group.Key;
            groupNode.Metadata = null;

            foreach (var classGroup in group
                         .GroupBy(e => e.SizeClass)
                         .OrderBy(g => g.Key, StringComparer.OrdinalIgnoreCase))
            {
                var classNode = VesselTree.AddItem(groupNode);
                classNode.Label.Text = classGroup.Key;
                classNode.Metadata = null;

                foreach (var vessel in classGroup.OrderBy(v => v.Name, StringComparer.OrdinalIgnoreCase))
                {
                    var vesselNode = VesselTree.AddItem(classNode);
                    vesselNode.Label.Text = vessel.Name;
                    vesselNode.Metadata = vessel.Id;
                }
            }

            groupNode.SetExpanded(false);
        }
    }

    private void OnTreeSelected(TreeItem? item)
    {
        var selected = VesselTree.SelectedItem;
        if (selected?.Metadata is not string id)
            return;

        if (!_byId.TryGetValue(id, out var entry))
            return;

        _catalog?.EnsureEquipment(entry);
        PopulateDetail(entry);
    }

    private void ClearDetail()
    {
        VesselTitleLabel.Text = _loc.GetString("vessel-reference-no-selection");
        StatsBox.RemoveAllChildren();
    }

    private void PopulateDetail(VesselReferenceEntry e)
    {
        VesselTitleLabel.Text = e.Name;
        StatsBox.RemoveAllChildren();

        void Row(string locKey, string value)
        {
            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal
            };

            box.AddChild(new Label
            {
                Text = _loc.GetString(locKey) + ":",
                MinWidth = 150,
                StyleClasses = { "LabelSubText" }
            });

            box.AddChild(new Label
            {
                Text = string.IsNullOrWhiteSpace(value)
                    ? _loc.GetString("vessel-reference-unknown")
                    : value,
                HorizontalExpand = true
            });

            StatsBox.AddChild(box);
        }

        Row("vessel-reference-price", BankSystemExtensions.ToSpesoString(e.Price));
        Row("vessel-reference-class", e.Classes.Count > 0
            ? string.Join(", ", e.Classes)
            : string.Empty);
        Row("vessel-reference-size", e.SizeClass);

        StatsBox.AddChild(new RichTextLabel
        {
            Text = e.Description,
            Margin = new Thickness(0, 12, 0, 4),
            VerticalExpand = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Top,
            HorizontalAlignment = HAlignment.Left,
            MaxWidth = 450
        });

        StatsBox.AddChild(new Label
        {
            Text = _loc.GetString("vessel-reference-equipment"),
            Margin = new Thickness(0, 12, 0, 4)
        });

        if (e.EquipmentByCategory.Count == 0)
        {
            StatsBox.AddChild(new Label
            {
                Text = _loc.GetString("vessel-reference-equipment-none")
            });
            return;
        }

        var categoryPriority = _protos
            .EnumeratePrototypes<VesselReferenceCategoryPrototype>()
            .ToDictionary(c => c.Name, c => c.Priority, StringComparer.OrdinalIgnoreCase);

        foreach (var (catKey, items) in e.EquipmentByCategory
                     .OrderBy(kv => categoryPriority.GetValueOrDefault(kv.Key, int.MaxValue))
                     .ThenBy(kv => kv.Key, StringComparer.OrdinalIgnoreCase))
        {
            StatsBox.AddChild(new Label
            {
                Text = _loc.GetString(catKey),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(0, 6, 0, 2)
            });

            foreach (var item in items)
            {
                StatsBox.AddChild(new Label
                {
                    Text = "- " + item,
                    Margin = new Thickness(8, 0, 0, 0)
                });
            }
        }
    }

    public void OpenToVessel(string vesselId)
    {
        if (!IsOpen)
            OpenCentered();

        Rebuild();

        if (_byId.TryGetValue(vesselId, out var entry))
        {
            _catalog?.EnsureEquipment(entry);
            PopulateDetail(entry);
        }
    }
}
